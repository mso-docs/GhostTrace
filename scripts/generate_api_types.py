#!/usr/bin/env python3
"""Generate checked-in TypeScript contracts from FastAPI OpenAPI; no network."""
from __future__ import annotations
import argparse
import json
import re
import tempfile
from pathlib import Path
from ghosttrace.api.app import create_app

ROOT=Path(__file__).resolve().parents[1]
def literal(value):return json.dumps(value,ensure_ascii=False)
def name(value):return re.sub(r'[^A-Za-z0-9_$]','_',value)
def ts(schema):
    if not isinstance(schema,dict):return 'unknown'
    if '$ref' in schema:return name(schema['$ref'].split('/')[-1])
    if 'const' in schema:return literal(schema['const'])
    if 'enum' in schema:return ' | '.join(literal(v) for v in schema['enum']) or 'never'
    for key,joiner in [('anyOf',' | '),('oneOf',' | '),('allOf',' & ')]:
        if key in schema:return '('+joiner.join(ts(item) for item in schema[key])+')'
    kind=schema.get('type')
    if isinstance(kind,list):return '('+' | '.join(ts({**schema,'type':k}) for k in kind)+')'
    if kind=='null':return 'null'
    if kind=='string':return 'string'
    if kind in ('integer','number'):return 'number'
    if kind=='boolean':return 'boolean'
    if kind=='array':return 'Array<'+ts(schema.get('items',{}))+'>'
    if kind=='object' or 'properties' in schema or 'additionalProperties' in schema:
        required=schema.get('required',[])
        fields=[literal(key)+('' if key in required else '?')+': '+ts(value)+';' for key,value in schema.get('properties',{}).items()]
        extra=schema.get('additionalProperties')
        if extra is True:fields.append('[key: string]: unknown;')
        elif isinstance(extra,dict):fields.append('[key: string]: '+ts(extra)+';')
        return '{ '+ ' '.join(fields)+' }'
    return 'unknown'

def generate():
    with tempfile.TemporaryDirectory() as directory:schema=create_app(directory).openapi()
    lines=['// Generated by scripts/generate_api_types.py. Do not edit by hand.','// Source: local FastAPI OpenAPI; schema_version 1.0.','']
    for key,value in sorted(schema.get('components',{}).get('schemas',{}).items()):lines.append('export type '+name(key)+' = '+ts(value)+';')
    lines+=['','export interface ApiOperations {']
    for path,methods in sorted(schema['paths'].items()):
        for method,operation in sorted(methods.items()):
            if method not in ('get','post','put','delete','patch'):continue
            body=operation.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema',{})
            responses=operation.get('responses',{});success=next((responses[k] for k in sorted(responses) if k.startswith('2')), {})
            response=success.get('content',{}).get('application/json',{}).get('schema',{})
            lines.append('  '+literal(method.upper()+' '+path)+': { request: '+ts(body)+'; response: '+ts(response)+' };')
    lines+=['}',''];return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');parser.add_argument('--output',default=str(ROOT/'web/src/generated/api-schema.ts'));args=parser.parse_args();path=Path(args.output);content=generate()
    if args.check:
        if not path.exists() or path.read_text()!=content:parser.exit(1,'Generated API types are stale. Run python scripts/generate_api_types.py\n')
        print('OpenAPI-generated TypeScript contracts are current.')
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content);print(str(path))
if __name__=='__main__':main()
